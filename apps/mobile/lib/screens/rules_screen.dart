// «قواعد اللعبة»: one tab per game, summarising docs/rules/*.md (the rules
// the server actually enforces). Opened from the table menu (on the current
// game's tab) and from the home screen's «القوانين» button.
import 'package:flutter/material.dart';
import 'package:google_fonts/google_fonts.dart';

import '../theme/samrah_theme.dart';
import '../widgets/motion.dart';

class RulesScreen extends StatelessWidget {
  const RulesScreen({super.key, this.variant = 'tarneeb'});

  /// Which tab opens first: the room's wire variant.
  final String variant;

  static const _tabs = ['طرنيب', 'طرنيب سوري 41', '400', 'تركس', '187', 'بلوت', 'هاند'];

  int get _initialTab => switch (variant) {
    'syrian41' => 1,
    'tarneeb400' => 2,
    'trix' || 'trixPartners' => 3,
    'b187' => 4,
    'baloot' => 5,
    'hand' => 6,
    _ => 0,
  };

  @override
  Widget build(BuildContext context) {
    return DefaultTabController(
      length: _tabs.length,
      initialIndex: _initialTab,
      child: Scaffold(
        appBar: AppBar(
          title: Text('قواعد اللعبة', style: GoogleFonts.cairo(fontSize: 20)),
          bottom: TabBar(
            isScrollable: true,
            tabAlignment: TabAlignment.start,
            indicatorColor: SamrahColors.text,
            labelColor: SamrahColors.text,
            unselectedLabelColor: SamrahColors.textMuted,
            labelStyle: const TextStyle(fontWeight: FontWeight.w700, fontSize: 14),
            tabs: [for (final t in _tabs) Tab(text: t)],
          ),
        ),
        body: const TabBarView(children: [_Tarneeb(), _Syrian(), _Four00(), _Trix(), _B187(), _Baloot(), _Hand()]),
      ),
    );
  }
}

