const esc = (s: string) => s.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]!);

function page(d: LegalDoc): string {
  const body = d.sections.map(([h, items]) => `<h2>${esc(h)}</h2><ul>${items.map((i) => `<li>${esc(i)}</li>`).join('')}</ul>`).join('');
  return `<!doctype html><html lang="ar" dir="rtl"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>${esc(d.title)} — سمرة</title>
<style>body{font-family:system-ui,sans-serif;background:#1b1b1b;color:#f5ead6;max-width:760px;margin:auto;padding:16px;line-height:1.8}h1{color:#fa8112}h2{color:#fa8112;font-size:18px;margin-top:24px}.muted{color:#aaa}</style>
</head><body><h1>${esc(d.title)}</h1><p class="muted">آخر تحديث: ${d.updated}</p>${body}</body></html>`;
}

